// Colours, radii and type sizes of the site come from the design tokens of the
// application (design/tokens.json, a copy of the file of HouseCairn/housecairn).
//
//   node scripts/tokens.mjs             write src/styles/tokens.css from design/tokens.json
//   node scripts/tokens.mjs --check     fail if src/styles/tokens.css is out of date
//   node scripts/tokens.mjs --upstream  also fail if design/tokens.json differs from the
//                                       file on the main branch of HouseCairn/housecairn
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "design/tokens.json";
const TARGET = "src/styles/tokens.css";
const UPSTREAM = "https://raw.githubusercontent.com/HouseCairn/housecairn/main/design/tokens.json";
// Groups used by the site; the variable is --<group>-<name>, as in the application.
const GROUPS = ["color", "font", "radius", "layout"];

function render(tokens) {
  const lines = [
    "/* Generated by scripts/tokens.mjs from design/tokens.json: do not edit. */",
    ":root {",
  ];
  for (const group of GROUPS) {
    for (const [name, value] of Object.entries(tokens[group] ?? {})) {
      lines.push(`  --${group}-${name}: ${value};`);
    }
  }
  lines.push("}", "");
  return lines.join("\n");
}

const raw = readFileSync(SOURCE, "utf8");
const css = render(JSON.parse(raw));
const args = new Set(process.argv.slice(2));

if (args.has("--upstream")) {
  const response = await fetch(UPSTREAM);
  if (!response.ok) throw new Error(`${UPSTREAM}: HTTP ${response.status}`);
  if ((await response.text()) !== raw) {
    console.error(`${SOURCE} differs from the application's tokens: copy ${UPSTREAM} and run npm run tokens.`);
    process.exit(1);
  }
  console.log(`${SOURCE} matches the application's tokens.`);
}
if (args.has("--check") || args.has("--upstream")) {
  let current = "";
  try { current = readFileSync(TARGET, "utf8"); } catch {}
  if (current !== css) {
    console.error(`${TARGET} is out of date: run npm run tokens.`);
    process.exit(1);
  }
  console.log(`${TARGET} is up to date.`);
} else {
  writeFileSync(TARGET, css);
  console.log(`wrote ${TARGET}`);
}
